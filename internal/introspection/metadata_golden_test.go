package introspection

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

// updateMetadataGolden regenerates the metadata golden files:
//
//	go test ./internal/introspection -run TestMetadataGolden -update
//
// A golden is keyed by the libvips version it was taken from, so raising the
// pinned libvips version produces a reviewable diff of exactly what the
// metadata does differently, instead of silent drift.
var updateMetadataGolden = flag.Bool("update", false, "rewrite the introspection metadata golden files")

// metadataLine projects one argument onto the fields the option-presence rule
// reads, so the golden stays reviewable rather than a dump of everything.
func metadataLine(dir string, arg Argument) string {
	def := "none"
	switch v := arg.DefaultValue.(type) {
	case nil:
	case bool:
		def = "bool:" + strconv.FormatBool(v)
	case int:
		def = "int:" + strconv.Itoa(v)
	case int64:
		def = "int64:" + strconv.FormatInt(v, 10)
	case float64:
		def = "float64:" + strconv.FormatFloat(v, 'g', -1, 64)
	case string:
		def = "string:" + strconv.Quote(v)
	default:
		def = fmt.Sprintf("unknown:%v", v)
	}
	vals := make([]string, 0, len(arg.EnumValues))
	for _, ev := range arg.EnumValues {
		vals = append(vals, strconv.Itoa(ev))
	}
	bound := func(set bool, v float64) string {
		if !set {
			return "-"
		}
		return strconv.FormatFloat(v, 'g', -1, 64)
	}
	return strings.Join([]string{
		arg.Name,
		dir,
		arg.GoType,
		fmt.Sprintf("flags=%t", arg.IsFlags),
		"default=" + def,
		fmt.Sprintf("range=%t", arg.HasRange),
		"min=" + bound(arg.HasMinimum, arg.Minimum),
		"max=" + bound(arg.HasMaximum, arg.Maximum),
		"members=" + strings.Join(vals, ","),
	}, "\t")
}

// TestMetadataGolden pins the introspected operation metadata for the running
// libvips version. There is no golden for a version this repository has not
// been generated against yet; that is a skip, not a failure.
func TestMetadataGolden(t *testing.T) {
	introspection := NewIntrospection(false)
	version := introspection.GetVipsVersion()
	if version == "" {
		t.Fatal("no libvips version reported")
	}
	path := filepath.Join("testdata", "metadata-"+version+".txt")

	operations := introspection.DiscoverOperations()
	if len(operations) == 0 {
		t.Fatal("no operations discovered")
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# libvips %s introspection metadata\n", version)
	fmt.Fprintf(&b, "# generated by: go test ./internal/introspection -run TestMetadataGolden -update\n")
	fmt.Fprintf(&b, "# columns: name, direction, goType, isFlags, default, hasRange, min, max, enumMembers\n")
	for _, op := range operations {
		fmt.Fprintf(&b, "%s\n", op.Name)
		for _, arg := range op.RequiredInputs {
			fmt.Fprintf(&b, "\t%s\n", metadataLine("required-input", arg))
		}
		for _, arg := range op.OptionalInputs {
			fmt.Fprintf(&b, "\t%s\n", metadataLine("optional-input", arg))
		}
		for _, arg := range op.RequiredOutputs {
			fmt.Fprintf(&b, "\t%s\n", metadataLine("required-output", arg))
		}
		for _, arg := range op.OptionalOutputs {
			fmt.Fprintf(&b, "\t%s\n", metadataLine("optional-output", arg))
		}
	}

	got := b.String()
	if *updateMetadataGolden {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s (%d lines)", path, strings.Count(got, "\n"))
		return
	}

	want, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		t.Skipf("no metadata golden for libvips %s; create it with: go test ./internal/introspection -run TestMetadataGolden -update", version)
	}
	if err != nil {
		t.Fatal(err)
	}
	if string(want) == got {
		return
	}
	// Report the first difference so the failure is readable.
	wantLines := strings.Split(string(want), "\n")
	gotLines := strings.Split(got, "\n")
	for i := 0; i < len(wantLines) || i < len(gotLines); i++ {
		var w, g string
		if i < len(wantLines) {
			w = wantLines[i]
		}
		if i < len(gotLines) {
			g = gotLines[i]
		}
		if w != g {
			t.Fatalf("metadata differs from %s at line %d:\n want: %s\n  got: %s", path, i+1, w, g)
		}
	}
}
